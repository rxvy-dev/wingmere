"""WINGMERE - builds data/airports.txt from OurAirports (public domain, https://ourairports.com).

Keeps every open large and medium airport, and small airports with a hard runway of at least
800 m, as long as at least one runway has coordinates for both ends.

Output, one airport per block:
  A ident|name|municipality|country|lat|lon|elev_m|type
  R le_ident|he_ident|le_lat|le_lon|he_lat|he_lon|width_m|le_elev_m|he_elev_m|surface(0 paved, 1 grass/dirt, 2 water)|lighted
"""
import csv, os
SRC = os.path.join(os.path.dirname(__file__), '..', 'assets_src', 'ourairports')
OUT = os.path.join(os.path.dirname(__file__), '..', 'data', 'airports.txt')

HARD = ('ASP', 'CON', 'PEM', 'BIT', 'TAR', 'PAV', 'MAC', 'COP')
def surface(s):
    s = (s or '').upper()
    if s.startswith('WAT'): return 2
    return 0 if any(s.startswith(h) for h in HARD) else 1

def f(x, d=None):
    try: return float(x)
    except (TypeError, ValueError): return d

runways = {}
for r in csv.DictReader(open(os.path.join(SRC, 'runways.csv'), encoding='utf-8')):
    if r['closed'] == '1': continue
    la1, lo1, la2, lo2 = f(r['le_latitude_deg']), f(r['le_longitude_deg']), f(r['he_latitude_deg']), f(r['he_longitude_deg'])
    if None in (la1, lo1, la2, lo2): continue
    runways.setdefault(r['airport_ident'], []).append(r)

n_ap = n_rw = 0
with open(OUT, 'w', encoding='utf-8') as out:
    out.write('# WINGMERE airports - generated by tools/build_airports.py from OurAirports (public domain)\n')
    for a in csv.DictReader(open(os.path.join(SRC, 'airports.csv'), encoding='utf-8')):
        t = a['type']
        if t not in ('large_airport', 'medium_airport', 'small_airport'): continue
        rws = runways.get(a['ident'])
        if not rws: continue
        if t == 'small_airport' and not any(surface(r['surface']) == 0 and (f(r['length_ft'], 0) or 0) >= 2600 for r in rws): continue
        elev = (f(a['elevation_ft'], 0) or 0) * 0.3048
        clean = lambda s: (s or '').replace('|', '/').strip()
        out.write('A %s|%s|%s|%s|%.6f|%.6f|%.1f|%s\n' % (a['ident'], clean(a['name']), clean(a['municipality']), a['iso_country'],
                                                        float(a['latitude_deg']), float(a['longitude_deg']), elev, t[0]))
        n_ap += 1
        for r in rws:
            w = max((f(r['width_ft'], 100) or 100) * 0.3048, 10)
            e1 = f(r['le_elevation_ft']); e2 = f(r['he_elevation_ft'])
            e1 = e1 * 0.3048 if e1 is not None else elev; e2 = e2 * 0.3048 if e2 is not None else elev
            out.write('R %s|%s|%.7f|%.7f|%.7f|%.7f|%.1f|%.1f|%.1f|%d|%s\n' % (clean(r['le_ident']), clean(r['he_ident']), float(r['le_latitude_deg']), float(r['le_longitude_deg']),
                                                                          float(r['he_latitude_deg']), float(r['he_longitude_deg']), w, e1, e2, surface(r['surface']), r['lighted'] or '0'))
            n_rw += 1
print(f'{n_ap} airports, {n_rw} runways -> {OUT} ({os.path.getsize(OUT) / 1e6:.1f} MB)')
